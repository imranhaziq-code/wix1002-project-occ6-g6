    private void addPlaceholder(final JTextField textField, final String placeholder) {
        textField.setText(placeholder);
        textField.setForeground(java.awt.Color.GRAY);

        textField.addFocusListener(new FocusAdapter() {
            @Override
            public void focusGained(FocusEvent e) {
                if (textField.getText().equals(placeholder)) {
                    textField.setText("");
                    textField.setForeground(java.awt.Color.BLACK);
                }
            }

            @Override
            public void focusLost(FocusEvent e) {
                if (textField.getText().isEmpty()) {
                    textField.setText(placeholder);
                    textField.setForeground(java.awt.Color.GRAY);
                }
            }
        });
    }

    private void addEyeIconListener(final JButton eyeButton, final JPasswordField passwordField) {
        eyeButton.addActionListener(new ActionListener() {
            private boolean isPasswordVisible = false;

            @Override
            public void actionPerformed(ActionEvent e) {
                if (isPasswordVisible) {
                    passwordField.setEchoChar('*');  // Hide password
                    isPasswordVisible = false;
                    eyeButton.setText("Show");
                } else {
                    passwordField.setEchoChar((char) 0);  // Show password
                    isPasswordVisible = true;
                    eyeButton.setText("Hide");
                }
            }
        });
    }
    
